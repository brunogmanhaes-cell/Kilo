-- 1. Criar tabela de usuários dedicada (NOTE_USERS)
CREATE TABLE NOTE_USERS (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME         VARCHAR2(64 CHAR) NOT NULL,
    EMAIL            VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD_HASH    VARCHAR2(255 CHAR) NOT NULL,
    IS_ADMIN         NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_NOTE_USERS_IS_ADMIN CHECK (IS_ADMIN IN (0, 1))
);

CREATE UNIQUE INDEX UQ_NOTE_USERS_USER_CI ON NOTE_USERS (LOWER(USERNAME));
CREATE UNIQUE INDEX UQ_NOTE_USERS_EMAIL_CI ON NOTE_USERS (LOWER(EMAIL));

-- 2. Adicionar coluna USER_ID em NOTES (inicialmente NULL para backfill do admin)
ALTER TABLE NOTES ADD (USER_ID NUMBER);

