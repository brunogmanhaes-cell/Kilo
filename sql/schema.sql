-- ============================================================================
-- 1. TABELA DE USUÁRIOS (Multi-usuário com suporte a administrador)
-- ============================================================================
CREATE TABLE NOTE_USERS (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME         VARCHAR2(64 CHAR) NOT NULL,
    EMAIL            VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD_HASH    VARCHAR2(255 CHAR) NOT NULL,
    IS_ADMIN         NUMBER(1) DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_NOTE_USERS_IS_ADMIN CHECK (IS_ADMIN IN (0, 1))
);

CREATE UNIQUE INDEX UQ_NOTE_USERS_USER_CI ON NOTE_USERS (LOWER(USERNAME));
CREATE UNIQUE INDEX UQ_NOTE_USERS_EMAIL_CI ON NOTE_USERS (LOWER(EMAIL));

-- ============================================================================
-- 2. TABELA DE NOTAS (Conteúdo HTML comprimido via zlib nível 9 por usuário)
-- ============================================================================
CREATE TABLE NOTES (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID          NUMBER NOT NULL,
    TITLE            VARCHAR2(255 CHAR) DEFAULT 'Sem título' NOT NULL,
    CONTENT_ZLIB     BLOB,
    RAW_TEXT_BYTES   NUMBER(12) DEFAULT 0 NOT NULL,
    COMP_TEXT_BYTES  NUMBER(12) DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTES_USER
        FOREIGN KEY (USER_ID)
        REFERENCES NOTE_USERS (ID)
        ON DELETE CASCADE
)
LOB (CONTENT_ZLIB) STORE AS SECUREFILE (
    ENABLE STORAGE IN ROW
    CHUNK 8192
    NOCACHE
    LOGGING
);

CREATE INDEX IDX_NOTES_UPDATED_AT ON NOTES (UPDATED_AT DESC);
CREATE INDEX IDX_NOTES_USER_UPDATED ON NOTES (USER_ID, UPDATED_AT DESC);

-- ============================================================================
-- 3. TABELA DE IMAGENS DAS NOTAS (Armazenamento lossless: WebP lossless / zlib)
-- ============================================================================
CREATE TABLE NOTE_IMAGES (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOTE_ID          NUMBER NOT NULL,
    IMAGE_WEBP       BLOB NOT NULL,
    WIDTH            NUMBER(5) NOT NULL,
    HEIGHT           NUMBER(5) NOT NULL,
    RAW_IMAGE_BYTES  NUMBER(12) NOT NULL,
    COMP_IMAGE_BYTES NUMBER(12) NOT NULL,
    MIME_TYPE        VARCHAR2(32 CHAR) DEFAULT 'image/webp' NOT NULL,
    IS_ZLIB          NUMBER(1) DEFAULT 0 NOT NULL,
    SHA256_HASH      VARCHAR2(64 CHAR),
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTE_IMAGES_NOTE
        FOREIGN KEY (NOTE_ID)
        REFERENCES NOTES (ID)
        ON DELETE CASCADE,
    CONSTRAINT CK_NOTE_IMAGES_IS_ZLIB CHECK (IS_ZLIB IN (0, 1))
)
LOB (IMAGE_WEBP) STORE AS SECUREFILE (
    ENABLE STORAGE IN ROW
    CHUNK 8192
    NOCACHE
    LOGGING
);

-- Índice obrigatório na FK para evitar table lock em DELETE CASCADE e acelerar agregações
CREATE INDEX IDX_NOTE_IMAGES_NOTE_ID ON NOTE_IMAGES (NOTE_ID);
