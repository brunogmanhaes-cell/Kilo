-- ============================================================================
-- 1. TABELA DE NOTAS (Conteúdo HTML/Texto comprimido via zlib nível 9)
-- ============================================================================
CREATE TABLE NOTES (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE            VARCHAR2(255 CHAR) DEFAULT 'Sem título' NOT NULL,
    CONTENT_ZLIB     BLOB,
    RAW_TEXT_BYTES   NUMBER(12) DEFAULT 0 NOT NULL,
    COMP_TEXT_BYTES  NUMBER(12) DEFAULT 0 NOT NULL,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
)
LOB (CONTENT_ZLIB) STORE AS SECUREFILE (
    ENABLE STORAGE IN ROW
    CHUNK 8192
    NOCACHE
    LOGGING
);

CREATE INDEX IDX_NOTES_UPDATED_AT ON NOTES (UPDATED_AT DESC);

-- ============================================================================
-- 2. TABELA DE IMAGENS DAS NOTAS (Convertidas para WebP 1280px q=72 method=6)
-- ============================================================================
CREATE TABLE NOTE_IMAGES (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOTE_ID          NUMBER NOT NULL,
    IMAGE_WEBP       BLOB NOT NULL,
    WIDTH            NUMBER(5) NOT NULL,
    HEIGHT           NUMBER(5) NOT NULL,
    RAW_IMAGE_BYTES  NUMBER(12) NOT NULL,
    COMP_IMAGE_BYTES NUMBER(12) NOT NULL,
    SHA256_HASH      VARCHAR2(64 CHAR),
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_NOTE_IMAGES_NOTE
        FOREIGN KEY (NOTE_ID)
        REFERENCES NOTES (ID)
        ON DELETE CASCADE
)
LOB (IMAGE_WEBP) STORE AS SECUREFILE (
    ENABLE STORAGE IN ROW
    CHUNK 8192
    NOCACHE
    LOGGING
);

-- Índice obrigatório na FK para evitar table lock em DELETE CASCADE e acelerar agregações
CREATE INDEX IDX_NOTE_IMAGES_NOTE_ID ON NOTE_IMAGES (NOTE_ID);
